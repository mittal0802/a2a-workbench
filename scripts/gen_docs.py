"""Generate the docs reference pages from code: health checks, CLI and configuration.

Usage: gen_docs.py [--check] [--out DIR]

Writes docs/reference/{checks,cli,configuration}.md (or into DIR). With --check,
writes nothing and exits 1 when any page differs from what the code produces.
"""

import argparse
import difflib
import sys
from pathlib import Path
from typing import Any

import typer

from a2a_workbench.cli.main import app
from a2a_workbench.core.config import Settings
from a2a_workbench.core.health.model import AREAS
from a2a_workbench.core.health.registry import builtin_checks

ROOT = Path(__file__).resolve().parents[1]
HEADER = "<!-- Generated by scripts/gen_docs.py from the code. Do not edit by hand. -->\n\n"


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def checks_page() -> str:
    """The health-check catalogue grouped by area."""
    checks = builtin_checks()
    out = [
        HEADER,
        "# Health checks\n\n",
        f"{len(checks)} checks. A failed **MUST** rule is a *fail*, a failed **SHOULD** rule a "
        "*warning*; a check whose feature the agent's card does not declare is *not supported* "
        "and not counted.\n",
    ]
    for area, name in AREAS.items():
        group = [c for c in checks if c.area == area]
        if not group:
            continue
        out.append(f"\n## {area} · {name}\n\n| Check | Rule | Level | Spec | How to fix |\n")
        out.append("|---|---|---|---|---|\n")
        for c in group:
            out.append(
                f"| `{c.id}` | {_cell(c.title)} | {c.level.upper()} | {_cell(c.spec_ref)} "
                f"| {_cell(c.fix_hint)} |\n"
            )
    return "".join(out)


def _commands(group: Any, prefix: str) -> list[tuple[str, Any]]:
    ctx = typer.Context(group)
    found: list[tuple[str, Any]] = []
    for name in sorted(group.list_commands(ctx)):
        cmd = group.get_command(ctx, name)
        if cmd is None or cmd.hidden:
            continue
        path = f"{prefix} {name}"
        if hasattr(cmd, "list_commands"):
            found.extend(_commands(cmd, path))
        else:
            found.append((path, cmd))
    return found


def _param_row(p: Any) -> str:
    if p.param_type_name == "argument":
        name = f"`{p.human_readable_name}`"
        kind = "argument" + ("" if p.required else ", optional")
        help_text = getattr(p, "help", None) or ""
    else:
        name = ", ".join(f"`{o}`" for o in [*p.opts, *p.secondary_opts])
        kind = "flag" if p.is_flag else "option"
        help_text = p.help or ""
        if not p.is_flag and p.default not in (None, (), "") and not callable(p.default):
            help_text += f" Default: `{p.default}`."
    return f"| {name} | {kind} | {_cell(help_text)} |\n"


def cli_page() -> str:
    """Every CLI command with its arguments and options."""
    root = typer.main.get_command(app)
    out = [
        HEADER,
        "# CLI reference\n\n",
        "Every command accepts `--help`. Commands with `--json` print one JSON document, or "
        "NDJSON for streams. Exit codes: `0` ok, `1` checks failed, `2` usage error, `3` "
        "connection error, `4` auth error, `5` protocol error, `6` internal error.\n",
    ]
    for path, cmd in _commands(root, "a2a-workbench"):
        out.append(f"\n## `{path}`\n\n{_cell(cmd.help or '')}\n")
        params = [p for p in cmd.params if p.name != "help"]
        if params:
            out.append("\n| Name | Kind | Description |\n|---|---|---|\n")
            out.extend(_param_row(p) for p in params)
    return "".join(out)


def configuration_page() -> str:
    """Environment variables read by the Workbench, with defaults."""
    out = [
        HEADER,
        "# Configuration\n\n",
        "Settings come from environment variables.\n\n",
        "| Variable | Default | Description |\n|---|---|---|\n",
    ]
    for name, field in Settings.model_fields.items():
        extra = field.json_schema_extra
        if isinstance(extra, dict) and extra.get("undocumented"):
            continue
        if name == "home":
            default = "`~/.a2a-workbench`"
        elif field.default in (None, ""):
            default = "—"
        else:
            default = f"`{field.default}`"
        out.append(f"| `A2AW_{name.upper()}` | {default} | {_cell(field.description or '')} |\n")
    return "".join(out)


PAGES = {"checks.md": checks_page, "cli.md": cli_page, "configuration.md": configuration_page}


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="Exit 1 if a page is out of date.")
    parser.add_argument("--out", type=Path, default=ROOT / "docs" / "reference")
    args = parser.parse_args()
    stale = False
    for name, render in PAGES.items():
        path: Path = args.out / name
        text = render()
        current = path.read_text() if path.exists() else ""
        if args.check:
            if current != text:
                stale = True
                sys.stdout.writelines(
                    difflib.unified_diff(
                        current.splitlines(keepends=True),
                        text.splitlines(keepends=True),
                        str(path),
                        "generated",
                        n=1,
                    )
                )
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if stale:
        print("\nReference docs are out of date: run scripts/gen_docs.py", file=sys.stderr)
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
